"""Модуль для разбора пользовательского ввода на команду и аргументы."""


def parse_input(user_input: str) -> tuple[str, list[str]]:
    """Разбирает строку ввода на имя команды и список аргументов.

    Args:
        user_input: Исходная строка, введённая пользователем.

    Returns:
        Кортеж из имени команды и списка аргументов. Для пустого
        ввода возвращает пару из пустой строки и пустого списка.
    """
    parts = user_input.strip().split()
    if not parts:
        return "", []

    return parts[0], parts[1:]
